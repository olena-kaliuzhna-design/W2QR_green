#!/usr/bin/env python3
"""Build content pages (content/*.html) into root-level pages in the Dusk layout.

Each content file starts with a front-matter comment:
  <!--
  title: Page title (HTML allowed)
  doctitle: optional plain title for <title>
  eyebrow: small label above the title
  sub: subtitle
  section: restore|tools|settings|help  (highlights the nav icon)
  layout: prose (default) | wide | docs | app
  -->
Live-site links (/terms, /docs/recovery …) are rewritten to local files.
Run:  python3 build.py
"""
import html, os, re, glob

ROOT = os.path.dirname(os.path.abspath(__file__))

ROUTES = {
    '/': 'index.html', '/restore': 'restore.html', '/wallet/open': 'restore.html',
    '/create': 'create.html', '/tools': 'tools.html', '/settings': 'settings.html', '/help': 'help.html',
    '/card': 'card.html', '/card/create': 'card.html', '/card/about': 'card-about.html',
    '/check-password': 'check-password.html', '/cloud-backup': 'cloud-backup.html',
    '/wallet/strong-password': 'strong-password.html', '/wallet/accounts': 'accounts.html',
    '/wallet/rotation': 'rotation.html', '/wallet/scanner': 'scanner.html',
    '/wallet/recover-mnemonic': 'recover-mnemonic.html', '/activate': 'activate.html',
    '/terms': 'terms.html', '/privacy': 'privacy.html', '/faq': 'faq.html', '/docs': 'docs.html',
    '/how-it-works': 'how-it-works.html', '/basic-vs-advanced': 'basic-vs-advanced.html',
    '/whitepaper': 'whitepaper.html', '/honey-encryption': 'honey-encryption.html',
    '/security': 'security.html', '/contact': 'contact.html',
}
for slug in ['getting-started', 'security-modes', 'how-encryption-works', 'recovery', 'balance-scanner',
             'security-model', 'wallet-compatibility', 'format-versions', 'card-wallet', 'plastic-cards']:
    ROUTES['/docs/' + slug] = 'docs-' + slug + '.html'

DOCS_NAV = [('/docs', 'Overview'), ('/docs/getting-started', 'Getting Started'),
            ('/docs/security-modes', 'Encryption & Backup'), ('/docs/how-encryption-works', 'How Encryption Works'),
            ('/docs/recovery', 'Recovery & Backup'), ('/docs/balance-scanner', 'Balance Scanner'),
            ('/docs/security-model', 'Security Model'), ('/docs/wallet-compatibility', 'Wallet Compatibility'),
            ('/docs/format-versions', 'QR Format Versions')]


def rewrite(s):
    def rep(m):
        url = m.group(1)
        return 'href="%s"' % ROUTES.get(url, url)
    return re.sub(r'href="(/[^"#?]*)"', rep, s)


def parse(path):
    raw = open(path, encoding='utf-8').read()
    m = re.match(r'\s*<!--(.*?)-->\s*', raw, re.S)
    meta = {}
    for line in m.group(1).strip().splitlines():
        k, _, v = line.partition(':')
        meta[k.strip()] = v.strip()
    return meta, raw[m.end():]


TEMPLATE = '''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{doctitle} — W2QR</title>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Geist:wght@300;400;500;600&family=Geist+Mono:wght@400;500&family=Manrope:wght@600;700;800&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="assets/css/styles.css">
  <link rel="stylesheet" href="assets/css/pages.css">
  <link rel="stylesheet" href="assets/css/docs.css">
  <link rel="stylesheet" href="assets/css/theme-c.css">
</head>
<body data-section="{section}" data-page="{page}">
  <!-- generated by build.py from content/{src} — edit the content file, then run build.py -->
  <div class="sky sky--page" aria-hidden="true"></div>
  <div id="site-header"></div>
  <main class="page {main_cls}">
{body}
  </main>
  <div id="site-footer"></div>
  <script src="assets/js/app.js"></script>
  <script src="assets/js/pages.js"></script>
</body>
</html>
'''


def head(meta):
    out = '    <div class="eyebrow">%s</div>\n    <h1 class="page-title">%s</h1>\n' % (html.escape(meta.get('eyebrow', '')), meta['title'])
    if meta.get('sub'):
        out += '    <p class="page-sub">%s</p>\n' % html.escape(meta['sub'])
    return out


def build(path):
    meta, content = parse(path)
    src = os.path.basename(path)
    out_name = src
    layout = meta.get('layout', 'prose')
    page = src[:-5]
    url = next((u for u, f in ROUTES.items() if f == out_name), None)
    if layout == 'docs':
        nav = '\n'.join('        <a href="%s"%s>%s</a>' % (ROUTES[u], ' aria-current="page"' if u == url else '', html.escape(t))
                        for u, t in DOCS_NAV)
        body = ('    <div class="docs">\n      <nav class="docs__nav" aria-label="Documentation">\n'
                '        <p class="docs__label">Documentation</p>\n%s\n      </nav>\n      <div class="docs__main">\n%s'
                '        <article class="prose">\n%s\n        </article>\n      </div>\n    </div>') % (nav, head(meta), content)
        cls = 'page--docs'
    elif layout == 'app':
        body = head(meta) + content
        cls = 'page--narrow'
    else:
        body = head(meta) + '    <article class="prose">\n' + content + '\n    </article>'
        cls = 'page--wide page--prose' if layout == 'wide' else 'page--prose'
    doctitle = meta.get('doctitle') or re.sub(r'<[^>]+>', ' ', meta['title'])
    doctitle = re.sub(r'\s+', ' ', doctitle).strip()
    out = TEMPLATE.format(doctitle=html.escape(doctitle), section=meta.get('section', ''), page=page,
                          src=src, main_cls=cls, body=rewrite(body))
    open(os.path.join(ROOT, out_name), 'w', encoding='utf-8').write(out)
    return out_name


if __name__ == '__main__':
    built = [build(p) for p in sorted(glob.glob(os.path.join(ROOT, 'content', '*.html')))]
    print('built', len(built), 'pages:', ', '.join(built))
